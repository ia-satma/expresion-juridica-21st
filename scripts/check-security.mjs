const secret = 'sk-proj-' + 'FAKE_TEST_ONLY_'.repeat(5), person = 'private-fixture@invalid.test';
const child = spawnSync(process.execPath, ['--input-type=module', '-e', `
  import './server/security-bootstrap.mjs';
  const secret = 'sk-proj-' + 'FAKE_TEST_ONLY_'.repeat(5);
  console.error('[cms]', new Error(secret + ' private-fixture@invalid.test'), { authorization: 'Bearer ' + secret, password: secret });
  console.log({ user: 'private-fixture@invalid.test', token: secret });
  throw new Error(secret + ' private-fixture@invalid.test');
`], { cwd: process.cwd(), encoding: 'utf8' });
assert.equal(child.status, 1);
const output = child.stdout + child.stderr;
assert(!output.includes(secret)); assert(!output.includes(person)); assert(!output.includes('Bearer')); assert(!output.includes('at file:'));
const records = output.trim().split('\n').map(line => JSON.parse(line));
assert(records.some(record => record.event === 'process.uncaught'));
assert(records.every(record => !Object.hasOwn(record, 'message') && !Object.hasOwn(record, 'stack') && !Object.hasOwn(record, 'user')));
assert.equal(publicFailure(new Error(secret)).error, 'INTERNAL_ERROR');
assert.equal(publicFailure(new Error('DOCUMENT_VERSION_CHANGED')).error, 'DOCUMENT_VERSION_CHANGED');
assert(hostedHttps({ REPLIT_DEPLOYMENT_URL: 'https://example.test' })); assert(hostedHttps({ REPL_ID: 'fixture' })); assert(!hostedHttps({}));
const session = applicationCookie('better-auth.session_token=fixture; Path=/', true);
assert(session.includes('; Secure')); assert(session.includes('; HttpOnly')); assert(session.includes('SameSite=Lax'));
const csrf = applicationCookie('cms_csrf=fixture; Path=/', true);
assert(csrf.includes('; Secure')); assert(!csrf.includes('HttpOnly'));
assert.equal(applicationCookie('GAESA=fixture; Path=/', true), 'GAESA=fixture; Path=/');
assert(allowedMedia({ originalname: 'foto.png', mimetype: 'image/png' }));
assert(allowedMedia({ originalname: 'documento.pdf', mimetype: 'application/octet-stream' }));
assert(!allowedMedia({ originalname: 'archivo.js', mimetype: 'application/octet-stream' }));
assert(!allowedMedia({ originalname: 'archivo.html', mimetype: 'image/png' }));
assert(!allowedMedia({ originalname: 'archivo.png', mimetype: 'text/javascript' }));
assert(safeMediaFilename('a123-fotografia.png'));
assert(!safeMediaFilename('directorio/imagen.png')); assert(!safeMediaFilename('directorio\\imagen.png')); assert(!safeMediaFilename('.archivo')); assert(!safeMediaFilename('imagen%2f.png'));

const app = express(); app.disable('x-powered-by');
app.use(securityMiddleware({ env: { NODE_ENV: 'production', PORT: '8798' } }));
app.use(express.json());
app.get('/api/cms/public', (_req, res) => res.json({ overrides: {}, settings: { analytics: { enabled: false }, navigation: { visibility: {} } } }));
app.get('/api/private-fixture', (_req, res) => res.set('Cache-Control', 'public, max-age=3600').cookie('cms_csrf', 'fixture').json({ ok: true }));
app.get('/api/error-fixture', (_req, res) => res.status(500).json({ error: secret, detail: person, stack: secret, headers: { authorization: secret } }));
app.post('/api/write-fixture', (_req, res) => res.json({ ok: true }));
app.get('/cms-media/fixture.svg', (_req, res) => res.type('image/svg+xml').send('<svg xmlns="http://www.w3.org/2000/svg"/>'));
const inventory = buildInventory();
const settings = { siteName: 'Expresión Jurídica Consultores', siteDescription: 'Prueba local de compatibilidad CSP', canonicalBaseUrl: 'https://expresion-juridica-21-st.replit.app', indexingEnabled: true, defaultLocale: 'es-MX', geo: {} };
