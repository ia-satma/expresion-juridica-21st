  const media = await fetch(base + '/cms-media/fixture.svg'); assert.match(media.headers.get('content-security-policy'), /script-src 'none'/); assert.match(media.headers.get('content-security-policy'), /sandbox/);
  const report = { passed: true, privateConsoleAndFatalErrors: true, safeApiFailures: true, applicationCookieFlags: true, csrfReadableByClient: true, privateNoStore: true, sameOriginWrites: true, uploadAllowlist: true, mediaSandbox: true, trustedInlineHashes: true, videoAndEditorPolicies: true };
  console.log(JSON.stringify(report));
